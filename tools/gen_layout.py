#!/usr/bin/env python3
"""Generate src/editor/Layout.h from docs/mockup/layout.json (made by tools/dump_layout.py from the approved
mockup). The native editor takes every position, size, label and tooltip from the mockup this way, so the
two cannot drift apart. Run from the repo root.
The mockup page has a preview rig (play button, test source) under the displays that is "not part of the
plugin". The real window leaves it out: 44 px shorter, and the footer moves up by that much. Tooltips that
talk about the preview rig are reworded for a plugin that plays whatever the host sends."""
import json
d = json.load(open('docs/mockup/layout.json'))
RIG = 44
R = d['rects']
for k in ('cheekL', 'cheekR', 'main'): R[k][3] -= RIG
for k in ('body', 'left', 'meters'): R[k][3] -= RIG
R['foot'][1] -= RIG; R['winsz'][1] -= RIG
foot = d['footTexts']
for t in foot: t['r'][1] -= RIG

REPL = [
    ('while the preview plays', 'while your audio plays'),
    ('Try pressing Play and raising Peak Reduction to watch it move.', 'Try playing audio and raising Peak Reduction to watch it move.'),
    ('while the preview plays, and match', 'while your audio plays, and match'),
]
def tip(s):
    for a, b in REPL: s = s.replace(a, b)
    return s
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
def f(v):
    t = '%g' % v
    if 'e' in t: t = '%.4f' % v
    return t + ('' if '.' in t else '.0') + 'f'
def rc(r): return '{ ' + ', '.join(f(v) for v in r) + ' }'
o = ['// GENERATED by tools/gen_layout.py from docs/mockup/layout.json. Do not edit by hand.', '#pragma once', 'namespace layout {',
     'struct Rc { float x, y, w, h; };', 'struct KnobCell { const char* id; bool big; Rc cell, lab, knob, val; const char* labText; const char* tip; };',
     'struct SegBtn { Rc r; const char* text; const char* tip; };', 'struct Cap { const char* text; Rc r; };',
     'constexpr int W = 1100, H = %d;' % (R['main'][3])]
for k in ['cheekL', 'cheekR', 'main', 'hdr', 'body', 'left', 'hw', 'disp', 'meters', 'foot', 'logo', 'name', 'badge', 's87', 'pPrev', 'pName', 'pNext', 'pSave',
          'bBypass', 'bGuide', 'bSettings', 'bAbout', 'vuwrap', 'cvVU', 'ears', 'segMeter', 'segMode', 'cvCurve', 'cvHist', 'cvFilt', 'cvIn', 'cvOut', 'pkIn', 'pkOut', 'winsz']:
    o.append('constexpr Rc %s = %s;' % ('mainArea' if k == 'main' else k, rc(R[k])))
for k in ['cheekTip']: o.append('constexpr const char* %s = %s;' % (k, q(d[k])))
for k in ['pPrev', 'pName', 'pNext', 'pSave', 'bBypass', 'bGuide', 'bSettings', 'bAbout', 'cvVU', 'cvCurve', 'cvHist', 'cvFilt', 'segMode', 'cvIn', 'cvOut', 'pkIn', 'pkOut']:
    o.append('constexpr const char* tip_%s = %s;' % (k, q(tip(d['tips'][k]))))
cells = []
for k in d['knobs']:
    cells.append('{ %s, %s, %s, %s, %s, %s, %s, %s }' % (q(k['id']), 'true' if k['big'] else 'false', rc(k['cell']), rc(k['lab']), rc(k['knob']), rc(k['val']), q(k['labText']), q(tip(k['tip']))))
o.append('constexpr KnobCell knobs[%d] = {\n    %s };' % (len(cells), ',\n    '.join(cells)))
def segs(name, arr): o.append('constexpr SegBtn %s[%d] = { %s };' % (name, len(arr), ', '.join('{ %s, %s, %s }' % (rc(b['r']), q(b['t']), q(tip(b['tip']))) for b in arr)))
segs('segMeterBtns', d['segMeterBtns']); segs('segModeBtns', d['segModeBtns'])
def caps(name, arr): o.append('constexpr Cap %s[%d] = { %s };' % (name, len(arr), ', '.join('{ %s, %s }' % (q(c['t']), rc(c['r'])) for c in arr)))
caps('dispCaps', d['dcaps']); caps('swCaps', d['swcaps']); caps('meterCaps', d['mcaps'])
o.append('constexpr Rc footLeft = %s;' % rc(foot[0]['r']))
o.append('} // namespace layout')
open('src/editor/Layout.h', 'w').write('\n'.join(o) + '\n')
print('ok H =', R['main'][3])
